#!/usr/bin/env python3
"""Prepare the isolated tree that publishes ffpa-attn under a second name.

The distribution name has to change before the build starts: ``name`` is a
static field of the ``[project]`` table, and setuptools only warns when
``setup(name=...)`` disagrees with it (``_MissingDynamic`` in
``setuptools/config/_apply_pyprojecttoml.py``). The release build therefore runs
in its own tree with a rewritten ``pyproject.toml``.

What is copied and what is symlinked: small inputs the build reads are copied
(``setup.py``, ``env.py``, ``src/``, ``csrc/``), large read-only ones are
symlinked (``third_party``'s CUTLASS headers, ``.git`` for setuptools-scm).
Copying the two writable trees is what keeps the developer checkout clean --
setuptools-scm rewrites ``src/ffpa_attn/_version.py`` with the release version,
the per-headdim translation units are generated under
``csrc/cuffpa/generated/``, and ``setup.py`` resolves its own root through
``Path(__file__).resolve()``, which would point back at the source tree if
``setup.py`` were a symlink.

Usage:
    tools/release_workspace.py --source-root . --workspace .tmp/release/py312 \\
        --package-name ffpa-attn [--version 0.2.4+cu13]
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

# Generated files that must not be carried over: the compiled extension (hundreds
# of MB, rebuilt here), the scm version file (written here), and the per-headdim
# translation units (regenerated here).
_IGNORE_SRC = shutil.ignore_patterns(
  "*.so", "*.pyd", "*.pyc", "__pycache__", "_version.py", "*.egg-info"
)
_IGNORE_CSRC = shutil.ignore_patterns("generated", "__pycache__")

# Copied: small, and the build writes into src/ and csrc/ (see the module docstring).
_COPIED_FILES = (
  "LICENSE", "MANIFEST.in", "README.md", "setup.py", "setup.cfg", "env.py"
)
# Symlinked: large and read-only for this build.
_LINKED_FILES = (".git", "third_party")
# Reached through the wrapper the release build calls; both must resolve to the
# workspace, which they do because build_fast.sh derives its repo root from $0.
_LINKED_TOOLS = ("build_fast.sh", "nvcc")


def _parse_args() -> argparse.Namespace:
  parser = argparse.ArgumentParser(
    description="Prepare an out-of-tree workspace for the ffpa-attn wheels."
  )
  parser.add_argument(
    "--source-root",
    required=True,
    help="Repository root containing pyproject.toml"
  )
  parser.add_argument(
    "--workspace",
    required=True,
    help="Workspace directory to create or refresh"
  )
  parser.add_argument(
    "--package-name",
    required=True,
    help="Distribution name for pyproject.toml"
  )
  parser.add_argument(
    "--version",
    default="",
    help="Release version to bake into src/ffpa_attn/_version.py; the build "
    "overwrites it with the same value when SETUPTOOLS_SCM_PRETEND_VERSION is set.",
  )
  parser.add_argument(
    "--incremental",
    action="store_true",
    help="Refresh an existing workspace instead of recreating it, so the "
    "compiled objects under build/ survive: the sources are re-copied, the "
    "build then relinks and repackages the wheel. Use it for a rebuild that "
    "changes only the version or other metadata.",
  )
  return parser.parse_args()


def _rewrite_pyproject(source: Path, target: Path, package_name: str) -> None:
  """Rename the distribution and the extras that refer to it by name.

  ``all = ["ffpa-attn[dev]", ...]`` has to name the release distribution too, or
  installing that extra resolves the pure-Python package from PyPI on top of the
  CUDA one -- two distributions owning the same ``ffpa_attn/`` directory.
  """
  text = source.read_text(encoding="utf-8")
  old_name = 'name = "ffpa-attn"'
  if text.count(old_name) != 1:
    raise RuntimeError(f"expected exactly one {old_name!r} in {source}")
  text = text.replace(old_name, f'name = "{package_name}"', 1)
  text = text.replace('"ffpa-attn[', f'"{package_name}[')
  target.write_text(text, encoding="utf-8")


def _symlink(target: Path, source: Path) -> None:
  target.parent.mkdir(parents=True, exist_ok=True)
  target.unlink(missing_ok=True)
  target.symlink_to(source)


def _write_version_file(package_dir: Path, version: str) -> None:
  package_dir.joinpath("_version.py").write_text(
    "# file generated by tools/release_workspace.py\n"
    f'version = "{version}"\n'
    f'__version__ = "{version}"\n',
    encoding="utf-8",
  )


def _assert_removable(source_root: Path, workspace: Path) -> None:
  """Refuse to remove something that could be the repository itself.

  Everything else here is repeatable; the rmtree is not, and --workspace takes
  an arbitrary path.
  """
  if workspace == source_root or source_root.is_relative_to(workspace):
    raise SystemExit(
      f"release_workspace: refusing to remove {workspace}: it is {source_root} "
      "or contains it"
    )
  if workspace == Path(workspace.anchor) or len(workspace.parts) < 3:
    raise SystemExit(
      f"release_workspace: refusing to remove {workspace}: too close to the "
      "filesystem root"
    )


def main() -> None:
  args = _parse_args()
  source_root = Path(args.source_root).resolve()
  workspace = Path(args.workspace).resolve()
  package_name = args.package_name

  if not (source_root / "pyproject.toml").is_file():
    raise SystemExit(
      f"release_workspace: no pyproject.toml under {source_root}"
    )

  if args.incremental:
    if not workspace.is_dir():
      raise SystemExit(
        f"release_workspace: --incremental needs an existing workspace, {workspace} is not one"
      )
  else:
    _assert_removable(source_root, workspace)
    if workspace.exists():
      shutil.rmtree(workspace)
  (workspace / "tools").mkdir(parents=True, exist_ok=True)

  _rewrite_pyproject(
    source_root / "pyproject.toml", workspace / "pyproject.toml", package_name
  )
  for name in _COPIED_FILES:
    shutil.copyfile(source_root / name, workspace / name)
  for name in _LINKED_FILES:
    _symlink(workspace / name, source_root / name)
  for name in _LINKED_TOOLS:
    _symlink(workspace / "tools" / name, source_root / "tools" / name)

  # copytree keeps mtimes, which is what lets an incremental build skip the
  # translation units whose sources did not move.
  shutil.copytree(
    source_root / "src",
    workspace / "src",
    ignore=_IGNORE_SRC,
    dirs_exist_ok=True
  )
  shutil.copytree(
    source_root / "csrc",
    workspace / "csrc",
    ignore=_IGNORE_CSRC,
    dirs_exist_ok=True
  )

  if args.version:
    _write_version_file(workspace / "src" / "ffpa_attn", args.version)

  copied = sorted(
    item.name for item in workspace.iterdir() if item.is_dir() or item.is_file()
  )
  print(f"[release_workspace] {workspace}")
  print(
    f"[release_workspace] distribution: {package_name}  version: {args.version or '<from scm>'}"
  )
  print(f"[release_workspace] entries: {' '.join(copied)}")


if __name__ == "__main__":
  main()
